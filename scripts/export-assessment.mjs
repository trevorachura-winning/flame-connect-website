// Export the assessment definition (content/assessment.ts) for the Python
// core, plus parity fixtures scored by the TypeScript implementation.
// Run: node scripts/export-assessment.mjs   (CI checks the output is current)
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const src = readFileSync("content/assessment.ts", "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
vm.runInNewContext(js, { module: mod, exports: mod.exports });
const { PILLARS, QUESTIONS, LEVELS, scoreAssessment } = mod.exports;

const data = {
  _comment: "Generated by scripts/export-assessment.mjs from content/assessment.ts. Do not edit.",
  pillars: PILLARS.map(({ key, name, nextStep }) => ({ key, name, nextStep })),
  questions: QUESTIONS.map(({ id, pillar }) => ({ id, pillar })),
  levels: LEVELS.map(({ min, name, summary }) => ({ min, name, summary })),
};

// Deterministic sample answer sets (simple LCG), plus edge cases.
let seed = 20261121;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const ids = QUESTIONS.map((q) => q.id);
const cases = [
  Object.fromEntries(ids.map((id) => [id, 1])),
  Object.fromEntries(ids.map((id) => [id, 4])),
  {},
];
for (let i = 0; i < 40; i++) cases.push(Object.fromEntries(ids.map((id) => [id, 1 + Math.floor(rnd() * 4)])));
const fixtures = cases.map((answers) => {
  const r = scoreAssessment(answers);
  return { answers, expected: { score: r.score, level: r.level.name, pillars: r.pillars.map((p) => [p.key, p.score]), nextSteps: r.nextSteps.map((n) => n.pillar) } };
});

writeFileSync("python/flame_core/assessment_data.json", JSON.stringify(data, null, 2) + "\n");
writeFileSync("tests/python/assessment_fixtures.json", JSON.stringify(fixtures) + "\n");
console.log(`exported ${data.questions.length} questions, ${fixtures.length} fixtures`);
